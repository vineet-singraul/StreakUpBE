import mongoose from 'mongoose';

const reportSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    date: { type: String, required: true }, // the day this report is about
    total: { type: Number, default: 0 },
    completedCount: { type: Number, default: 0 },
    completed: { type: [String], default: [] },
    pending: {
      type: [
        {
          task: { type: mongoose.Schema.Types.ObjectId, ref: 'Task' },
          title: String,
          reason: { type: String, default: '' },
        },
      ],
      default: [],
    },
    aiSummary: { type: String, default: '' },
    // true = generated by the 12 AM job (day is over); false = on-demand preview during the day
    final: { type: Boolean, default: false },
    reasonsSubmitted: { type: Boolean, default: false },
    aiFeedback: { type: String, default: '' },
    generatedAt: Date,
  },
  { timestamps: true },
);

reportSchema.index({ user: 1, date: 1 }, { unique: true });

export default mongoose.model('Report', reportSchema);
